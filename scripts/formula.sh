#!/usr/bin/env bash
# Usage: formula.sh <version>
# Prints Formula/relay.rb for FunDrivenDev/homebrew-tap: relay <version>'s
# Linux archives on its GitHub release, with their sha256 read from
# dist/checksums.txt (the one `just release publish` left). Stdout only:
#   scripts/formula.sh 1.2.3 >../homebrew-tap/Formula/relay.rb
set -euo pipefail

[[ $# -eq 1 ]] || {
    echo "usage: formula.sh <version>" >&2
    exit 2
}
version=${1#v}
[[ $version =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || {
    echo "formula.sh: $1 is not a version X.Y.Z" >&2
    exit 2
}
sums=dist/checksums.txt
[[ -f $sums ]] || {
    echo "formula.sh: no $sums: run just release publish first" >&2
    exit 1
}

sha() {
    local archive="relay_linux_$1.tar.gz" sum
    sum=$(grep " $archive\$" "$sums" | sed 's/ .*//')
    [[ -n $sum ]] || {
        echo "formula.sh: $archive is not in $sums" >&2
        exit 1
    }
    echo "$sum"
}
arm64=$(sha arm64)
amd64=$(sha amd64)
url="https://github.com/FunDrivenDev/relay/releases/download/v#{version}"

cat <<RUBY
# The formula of relay, generated by relay's scripts/formula.sh from the
# checksums of its v${version} release.
class Relay < Formula
  desc "Claude Code sessions under tmux, with the handover relay and AFK runs"
  homepage "https://github.com/FunDrivenDev/relay"
  version "${version}"
  license "MIT"

  depends_on :linux
  depends_on "tmux"

  on_linux do
    on_arm do
      url "${url}/relay_linux_arm64.tar.gz"
      sha256 "${arm64}"
    end
    on_intel do
      url "${url}/relay_linux_amd64.tar.gz"
      sha256 "${amd64}"
    end
  end

  def install
    bin.install "relay"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/relay --version")
  end
end
RUBY
